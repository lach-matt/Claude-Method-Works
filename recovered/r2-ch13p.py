def lat_closure(y):
    """|sublattice generated by Λ₈ ∪ {y}|, y a thermometer code."""
    cells = np.append(E8, np.uint32(y))
    srt = np.unique(cells)
    front = np.array([np.uint32(y)], dtype=np.uint32)
    while len(front):
        o = np.bitwise_or(srt[None, :], front[:, None]).ravel()
        a = np.bitwise_and(srt[None, :], front[:, None]).ravel()
        u = np.unique(np.concatenate([o, a]))
        new = u[~np.isin(u, srt, assume_unique=True)]
        if not len(new):
            break
        srt = np.union1d(srt, new); front = new
    return len(srt)


def Rtree(X, edges):
    """ℛ restricted to a given edge set: Rset's sweep with phi kept only on those pairs."""
    A = np.array(sorted(set(X)), dtype=np.int64); d = A.shape[1]
    vals = [np.unique(A[:, i]) for i in range(d)]
    keep = set()
    for (i, j) in edges:
        keep.add((i, j)); keep.add((j, i))
    phi = {}
    for (i, j) in keep:
        m = np.full(int(A[:, j].max()) + 1, -1, dtype=np.int64)
        for v in vals[j]:
            m[v] = A[A[:, j] <= v, i].max()
        phi[(i, j)] = m
    G = np.array(np.meshgrid(*vals, indexing='ij')).reshape(d, -1).T
    ok = np.ones(len(G), dtype=bool)
    for (i, j), m in phi.items():
        ok &= G[:, i] <= m[G[:, j]]
    return set(map(tuple, G[ok]))


