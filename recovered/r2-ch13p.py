def therm(t):
    v = 0
    for i, x in enumerate(t):
        v |= ((1 << (x + 1)) - 1) << (4 * i)
    return np.uint32(v)


def untherm(v):
    v = int(v)
    return tuple(bin((v >> (4 * i)) & 15).count('1') - 1 for i in range(8))


