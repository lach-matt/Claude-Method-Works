def block(z):
    l = E[z][1]
    return ['s','p','d','f'][l] if l <= 3 else 'g'

def maxk(l):
    return 2*(2*l+1)

def Q0mag(z):
    n,l,k = E[z]
    return np.sqrt(n*n + l*l + k*k)

def hcp(z):
    """Heuristic host-coupling index H_cp. Exponent l/4 is a CHOICE, not derived."""
    n,l,k = E[z]
    f = 1.0 if l == 0 else (k/maxk(l))**(l/4.0)
    return Q0mag(z) * f

def deltaQ(z):
    """Displacement Q0 - midpoint(Q1,Q2) per Lach eq (3)."""
    n,l,k = E[z]
    Q0 = np.array([n,l,k], float)
    Q1 = np.array([n+1,l,k], float)
    if l+1 <= n-1:
        Q2 = np.array([n,l+1,k], float)
    elif l > 0:
        Q2 = np.array([n,l-1,k], float)
    else:
        Q2 = np.array([n+1,l,k], float)
    return Q0 - 0.5*(Q1+Q2), Q1, Q2

def dclass(z):
    """Direction class of DeltaQ."""
    n,l,k = E[z]
    if l+1 <= n-1: return 'B'
    elif l > 0:    return 'C'
    else:          return 'A'

