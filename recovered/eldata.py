# Cell classification counts (7 x 5 x 18 lattice)
def classify_cells():
    void = reactive = reserved = occupied = 0
    occ = set(E[z] for z in E)
    for n in range(1,8):
        for l in range(0,5):
            for k in range(1,19):
                if l >= n:
                    void += 1
                elif k > maxk(l):
                    reactive += 1
                elif (n,l,k) in occ:
                    occupied += 1
                else:
                    reserved += 1
    return dict(void=void, reactive=reactive, reserved=reserved, occupied=occupied)

