# ============ RUN THE METHOD OVER EVERYTHING ============
rows = []
for sp, (grp, I, Z, CH) in SETS.items():
    for l, M in CH.items():
        ns = sorted(M)
        for n in ns:
            o = [m for m in ns if m != n]
            if not (any(m < n for m in o) and any(m > n for m in o)):
                continue
            near = sorted(o, key=lambda m: abs(m - n))[:6]
            if len(near) < 3:
                continue
            d = np.array([m - np.sqrt(Z*Z*R/(I - M[m])) for m in near])
            x = 1.0/np.array(near, float)**2
            k = len(near); A = np.vstack([np.ones(k), x]).T
            b, *_ = np.linalg.lstsq(A, d, rcond=None)
            res = d - A @ b
            s = np.sqrt(max((res**2).sum(), 0)/max(k - 2, 1))
            x0 = 1/n**2; xb = x.mean(); Sxx = max(((x - xb)**2).sum(), 1e-30)
            sd = s*np.sqrt(1 + 1/k + (x0 - xb)**2/Sxx)
            nu = n - (b[0] + b[1]*x0)
            er = abs((I - Z*Z*R/nu**2) - M[n]); sg = 2*Z*Z*R*sd/nu**3
            L = max(M[m] for m in o if m < n); U = min(M[m] for m in o if m > n)
            rows.append((grp, sp, l, n, er, sg, L <= M[n] <= U))

E = np.array([r[4] for r in rows]); S = np.array([r[5] for r in rows])
