def run(name,E):
    T={k:I-v for k,v in E.items()}
    print(f"\n===== He I {name} =====")
    for l in range(4):
        row=[(n,n-math.sqrt(R/T[(n,l)])) for n in range(2,17) if (n,l) in T]
        if row: print(f"  l={l} delta: "+" ".join(f"{n}:{d:+.5f}" for n,d in row[:8]))
    v=t=0; badn=[]
    for n in range(2,17):
        ts=[(l,T[(n,l)]) for l in range(4) if (n,l) in T]
        if len(ts)<2: continue
        bad=[(ts[i][0],ts[i+1][0]) for i in range(len(ts)-1) if ts[i+1][1]>ts[i][1]]
        t+=len(ts)-1; v+=len(bad)
        if bad: badn.append((n,bad))
    print(f"  T monotone in l: {t} comparisons, {v} VIOLATIONS")
    for n,b in badn[:6]: print(f"     n={n}: rises at {b}")
    rats=[];viol=[]
    for (n,l) in sorted(T):
        if (n+1,l) not in T or (n-1,l) not in T: continue
        up=[T[c] for c in [(n+1,l),(n,l+1)] if c in T]
        dn=[T[c] for c in [(n-1,l),(n,l-1)] if c in T]
        if len(up)<2 or len(dn)<2: continue
        lo,hi=max(up),min(dn); ok=lo<=T[(n,l)]<=hi
        if not ok: viol.append((n,'spdf'[l]))
        wc=T[(n-1,l)]-T[(n+1,l)]; rats.append((hi-lo)/wc)
    print(f"  lattice bracket: {len(rats)} cells, VIOLATIONS {len(viol)} {viol}")
    if rats: print(f"  mean ratio {sum(rats)/len(rats):.4f}")
    return len(viol),len(rats)
