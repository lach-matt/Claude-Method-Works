import pickle, numpy as np, random
from itertools import combinations, product, permutations
random.seed(613)
D=pickle.load(open('/home/claude/stage/s1.pkl','rb'))
res=pickle.load(open('/home/claude/stage/s2.pkl','rb'))
cells=D['cells']; tab=D['tab']; NF=D['nforms']; n=len(cells)
DIMS=D['dims']; d=len(DIMS)
CIDX={c:i for i,c in enumerate(cells)}
print("="*88)
print("  LET THE SURROUNDING DEFINITIONS BUILD THE TABLE")
print("="*88)
print("""
  **The mistake.** I was trying to construct the YES table by exhausting the
  box — 260,800 subsets — because I wanted the missing definition directly.

  **The surrounding definitions already generate it.** The YES set is closed
  under the six preserving rules, and the identity of reorderable-with-
  sublattice means: **every reorderable set is a sublattice in SOME order.**
  So GENERATE sublattices in every order and read off their signatures.

     no exhaustion · no search · the grammar does the work
""")
def sig(S):
    idx=sorted(CIDX[c] for c in S)
    c=[0]*NF
    for T in combinations(idx,3): c[tab[T]]+=1
    return tuple(c)
def is_sublat(S):
    Ss=set(S)
    for x,y in combinations(sorted(S),2):
        if tuple(max(x[i],y[i]) for i in range(d)) not in Ss: return False
        if tuple(min(x[i],y[i]) for i in range(d)) not in Ss: return False
    return True
def alph(S): return [sorted({x[i] for x in S}) for i in range(d)]
def relab(S,o):
    ix=[{v:i for i,v in enumerate(p)} for p in o]
    return {tuple(ix[k][x[k]] for k in range(d)) for x in S}
print("="*88)
print("  GENERATE: sublattices of the box, in every relabelling")
print("="*88)
ORD=list(product(*[list(permutations(range(x))) for x in DIMS]))
print("\n     relabellings of the box : %d"%len(ORD))
# enumerate sublattices of the box directly, by closing seeds
subl=set()
allc=set(cells)
t=0
for m in range(1,1<<n):
    S={cells[i] for i in range(n) if m>>i & 1}
    A=alph(S)
    if any(len(x)<2 for x in A): continue
    t+=1
    if is_sublat(S): subl.add(frozenset(S))
print("     subsets with ≥2 values per axis : %d"%t)
print("     of those, SUBLATTICES in place  : %d"%len(subl))
# now the YES signatures = signatures of every relabelling of every sublattice
gen=set()
for S in subl:
    for ps in ORD:
        T=relab(S,[list(p) for p in ps])
        A=alph(T)
        if any(len(x)<2 for x in A): continue
        gen.add(sig(T))
print("     **YES signatures generated      : %d**"%len(gen))
print("="*88)
print("  COMPARE TO THE EXHAUSTIVE ANSWER")
print("="*88)
cls={}
for mask in range(1,1<<n):
    v=res[mask]
    if not v: continue
    idx=[i for i in range(n) if mask>>i & 1]
    c=[0]*NF
    for T in combinations(idx,3): c[tab[T]]+=1
    k=tuple(c)
    if k not in cls: cls[k]=v
Yex={k for k,v in cls.items() if v==2}
Nex={k for k,v in cls.items() if v==1}
print("\n     exhaustive YES signatures : %d"%len(Yex))
print("     generated YES signatures  : %d"%len(gen))
