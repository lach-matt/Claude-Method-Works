def headline(rows):
    """The answer, per account (never mixing clashing premises), led by member-attributed removals.  Returns the
    maxima and the variants attaining each, the smallest first."""
    cons = [r for r in rows if r["consistent"]]
    stats = []
    for r in cons:
        for a in account_view(r)[0]:
            stats.append((r, a))
    out = {}
    for name, f in (("member_removed", lambda a: len(a["member_removed"])),
                    ("not_bound", lambda a: len(a["not_bound"])),
                    ("no_member_removed", lambda a: len(a["no_member_removed"])),
                    ("removed_or_nb (history figure, per account)", lambda a: len(a["removed_or_nb"])),
                    ("removed only (member or not)", lambda a: len(a["member_removed"]) + len(a["no_member_removed"]))):
        m = max(f(a) for _, a in stats)
        att = sorted({tuple(r["present"]) for r, a in stats if f(a) == m}, key=lambda t: (len(t), t))
        out[name] = {"max": m, "variants": len(att), "smallest": list(att[0]) if att else None}
    which = {}
    for r, a in stats:
        for o in a["member_removed"]:
            which.setdefault(o, set()).add(tuple(r["present"]))
    out["member_removed_by_obstruction"] = {o: {"variants": len(v), "smallest": list(min(v, key=lambda t: (len(t), t)))}
                                            for o, v in which.items()}
    # the most member-attributed results in ONE account: removals first, then not-bound
    best = max(stats, key=lambda ra: (len(ra[1]["member_removed"]), len(ra[1]["not_bound"]),
                                      -len(ra[0]["present"])))
    out["best"] = {"variant": best[0]["present"], "premises_dropped": sorted(set(NAMED) - set(best[1]["premises"])),
                   "five": best[1]["five"], "seven": best[1]["seven"]}
    return out


