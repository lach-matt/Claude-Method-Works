def _strip_parens(t):
    """Remove every parenthetical, innermost first (P1)."""
    prev = None
    while prev != t:
        prev, t = t, re.sub(r"\([^()]*\)", "", t)
    return t


def parse_report_class(text, present, grade=None, G=None, rid=None):
    """The A-report's per-obstruction text -> one class: R (REMOVED / REMOVED-IF), NB (NOT-BOUND-IF), OPEN, N (LEAVES /
    LEFT / SILENT / REINTRODUCED -- 'not removed by this hypothesis'), CLASH.  Rules, stated (wave 3 changes marked):
      P2 'as H-SETTLE-W' resolves to that grade's text;
      P4 a '(measure); ... (corridor)' text is read on its corridor clause; a NOT-BOUND-IF whose premise names H-IT,
         in a variant without H-IT, is N (the grade's own conditional is unmet);
      P7 (wave 3) a text split by H-IT reading ('ITE: ...; ITB: ...; ITJ: ...', A4's split rows) is read on the
         clause for the variant's reading, the unlabelled leading clause applying otherwise;
      P1 (wave 3: generalised) every parenthetical is dropped -- wave 2 dropped only '(A1: ...)' citations, and a
         grade that cites another grade's removal in parentheses ('LEFT by this pair (... REMOVED-IF ...)') was then
         read as R;
      P8 (wave 3) the class is read on the FIRST clause (to the first ';' outside braces), the later clauses being
         qualifications -- wave 2 read the whole text, so 'REINTRODUCED ...; Hawking's conjecture OPEN' read OPEN;
      P9 (wave 3) 'LEFT-IF {premises}' is OPEN: left only under named premises, undecided outside them (A4's
         R-QUANTUM, RV-1 #5);
      P3 precedence within the clause: CLASH > NOT-BOUND-IF > REMOVED-IF > OPEN / LEFT-IF > the rest."""
    t = text
    if t.startswith("as H-SETTLE-W") and G is not None:
        g0 = _grade(G, "A1-settle", "H-SETTLE-W (M's definition")
        return None if g0 is None else ("ALIAS", g0)
    if "(corridor)" in t:
        t = t.split(";")[-1]
    if re.search(r"\bIT[EBJ]:", t):
        segs = re.split(r";\s*(?=IT[EBJ]:)", t)
        mine = [x for x in segs if x[:4].rstrip(":") in present]
        lead = [x for x in segs if not re.match(r"IT[EBJ]:", x)]
        t = (mine or lead or [""])[0]
    t = _strip_parens(t)
    depth, cut = 0, len(t)
    for i, ch in enumerate(t):
        depth += (ch == "{") - (ch == "}")
        if ch == ";" and depth == 0:
            cut = i
            break
    t = t[:cut]
    if "CLASH" in t:
        return "CLASH"
    if "NOT-BOUND-IF" in t:
        if "H-IT" in t and not (IT_READ & set(present)):
            return "N"
        return "NB"
    if "REMOVED-IF" in t or t.strip().startswith("REMOVED"):
        return "R"
    if "OPEN" in t or "LEFT-IF" in t:
        return "OPEN"
    return "N"


