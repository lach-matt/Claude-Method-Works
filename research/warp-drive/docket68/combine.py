def markdown_table(R):
    au = {}
    for r in R["rows_au"]:
        au.setdefault(tuple(r["combo"]) or ("(readings only)",), []).append(r)
    by = {}
    for r in R["rows"]:
        by.setdefault(tuple(r["combo"]) or ("(readings only)",), []).append(r)
    out = ["| # | combination | variants | consistent | clash (literals in core) | premise clashes | best variant "
           "(one account) | BITS/TOPO/DIST/HOLD/SEAT/LOOP-C/LOOP-S | member-attributed removals | NOT-BOUND-IF | "
           "removed with no member (geometry / board / premise) | load-bearing members; adds nothing | joint / "
           "independent variants | 1 AU, N = 7: W2 variants with O-BITS member-removed |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for i, t in enumerate(R["table"], 1):
        key = tuple(t["combo"])
        name = "+".join(ABBR.get(h, h) for h in key)
        cl = "; ".join(t["clashes"]) or "-"
        pc = "; ".join(t["premise_clashes"]) or "-"
        if "best_variant" in t:
            best = next(r for r in by[key] if r["present"] == t["best_variant"])
            acc = account_view(best)[1]
            codes = "/".join(_code(best, acc, o) for o in OBST)
            bv = ",".join(t["best_variant"]) + (f" (dropped {', '.join(t['best_account_premises_dropped'])})"
                                                 if t["best_account_premises_dropped"] else "")
            mem = ",".join(x.replace("O-", "") for x in t["member_removed"]) or "none"
            nb = ",".join(x.replace("O-", "") for x in t["not_bound"]) or "-"
            nm = ",".join(x.replace("O-", "") for x in t["no_member_removed"]) or "-"
            lb = (",".join(t["load_bearing"]) or "none") + ("; adds nothing: " + ",".join(t["adds_nothing"])
                                                             if t["adds_nothing"] else "")
        else:
            codes = bv = mem = nb = nm = lb = "-"
        lst = au.get(key, [])
        a = sum(1 for r in lst if r["consistent"] and any(ac["per"]["O-BITS"] == "Rm" for ac in r["accounts"]))
        acol = f"{a}/{len(lst)}" if lst else "-"
