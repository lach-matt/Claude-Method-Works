def untested(rows, cell):
    reasons = {v: 0 for v in UNTESTED_REASONS.values()}
    listed = []
    for r in rows:
        if not r["consistent"]:
            reason = UNTESTED_REASONS["inc"]
        elif r.get("joint"):
            continue
        elif r.get("independent"):
            reason = UNTESTED_REASONS["indep"]
        elif not r["attributed"]:
            reason = UNTESTED_REASONS["none"]
        else:
            reason = UNTESTED_REASONS["single"]
        reasons[reason] += 1
        listed.append((cell, r["present"], reason))
    return reasons, listed


