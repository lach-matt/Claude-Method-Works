import sys
from fractions import Fraction as Fr

FAIL = []
HALF = Fr(1, 2)


def check(name, ok, msg=""):
    print(f"  {name}: {'pass' if ok else 'FAIL'} {msg}")
    if not ok:
        FAIL.append(name)


class Ctx:
    def __init__(self, g, e, top):
        self.g, self.e, self.top = g, e, top
        self.d = (1 - e) * g
        self.sigma = [(Fr(0), 0, 0), (Fr(0), 1, 0), (Fr(0), 0, 1), (Fr(0), 0, 2)]

    def val(self, z):
        return z[0] + z[1] * self.d + z[2] * self.g

    def ok(self, z):
        return self.val(z) <= self.top


def add(z, w):
    return (z[0] + w[0], z[1] + w[1], z[2] + w[2])


def close(C, E):
    """+1 closure (logs carried) below the top"""
    out = dict(E)
    for z in sorted(E, key=C.val):
        k = out[z]
        y = (z[0] + 1, z[1], z[2])
        while C.ok(y):
            if out.get(y, -1) < k:
                out[y] = k
            y = (y[0] + 1, y[1], y[2])
    return out


def union(E, F):
    out = dict(E)
    for z, k in F.items():
        out[z] = max(out.get(z, -1), k)
    return out


def ext_union(E, F):
    out = union(E, F)
    for z in set(E) & set(F):
        out[z] = E[z] + F[z] + 1
    return out


def tot(C, E):
    return union(E, {(Fr(3, 2) + s[0], s[1], s[2]): 0 for s in C.sigma})


def sum_minus1(C, A, B):
    out = {}
    for a, ka in A.items():
        for b, kb in B.items():
            z = (a[0] + b[0] - 1, a[1] + b[1], a[2] + b[2])
            if C.ok(z):
                out[z] = max(out.get(z, -1), ka + kb)
    return out


def least_def31(C, seed):
    """III.C Lemma 3.2 (e): the least E^C_I containing seed with E^tot + (E^tot - 1) in E^C_I"""
    E = close(C, dict(seed))
    while True:
        T = tot(C, E)
        new = close(C, union(E, sum_minus1(C, T, T)))
        if new == E:
            return E
        E = new


def F_of(C, G):
    T = tot(C, G)
    return close(C, sum_minus1(C, T, T))


def sharp(C, E0):
    """G = E_0 u-bar F(G), the least fixed point (fixed-point iteration from the empty set)"""
    G = {}
    for _ in range(400):
        new = close(C, ext_union(E0, F_of(C, G)))
        if new == G:
            return G
        G = new
    raise RuntimeError("no fixed point")


def sharp_recursive(C, E0):
    """the same set by explicit recursion on the real part"""
    cand = set(E0)
    T0 = tot(C, {})
    # every exponent reachable: generate the formal lattice below top
    frontier = set(T0) | set(E0)
    allz = set(frontier)
    while frontier:
        new = set()
        for a in frontier:
            for b in allz | set(T0):
                z = (a[0] + b[0] - 1, a[1] + b[1], a[2] + b[2])
                if C.ok(z) and z not in allz:
                    new.add(z)
            y = (a[0] + 1, a[1], a[2])
            if C.ok(y) and y not in allz:
                new.add(y)
        allz |= new
        frontier = new
    allz |= cand
    G = {}
    for z in sorted(allz, key=C.val):
        if not C.ok(z):
            continue
        T = tot(C, {w: k for w, k in G.items() if C.val(w) <= C.val(z) - HALF})
        kF = -1
        for a, ka in T.items():
            for b, kb in T.items():
                if (a[0] + b[0] - 1, a[1] + b[1], a[2] + b[2]) == z:
                    kF = max(kF, ka + kb)
        # +1 closure of F: z - 1 in F(G) (F is +1-closed and is computed from the lower part)
        y = (z[0] - 1, z[1], z[2])
        if y in G:
            Fy = None
            Tl = tot(C, {w: k for w, k in G.items() if C.val(w) <= C.val(y) - HALF})
            for a, ka in Tl.items():
                for b, kb in Tl.items():
                    if (a[0] + b[0] - 1, a[1] + b[1], a[2] + b[2]) == y:
                        Fy = ka + kb if Fy is None else max(Fy, ka + kb)
            # F's +1 closure is by induction on F itself
        kF = max(kF, FCACHE.get((id(C), y), -1))
        FCACHE[(id(C), z)] = kF
        k0 = E0.get(z, -1)
        if k0 >= 0 and kF >= 0:
            G[z] = k0 + kF + 1
        elif k0 >= 0:
            G[z] = k0
        elif kF >= 0:
            G[z] = kF
    return close(C, G)


FCACHE = {}


def subset(A, B):
    return all(B.get(z, -1) >= k for z, k in A.items())


def E0_int(C):
    return close(C, {(Fr(2), 0, 0): 0})


def E0_half(C):
    return close(C, {(Fr(2), 0, 0): 0, (Fr(5, 2), 0, 0): 0})


def halfpts(lo, hi):
    out, z = [], Fr(lo)
    while z <= hi:
        out.append(z)
        z += HALF
    return out


def logs_at(E, pts):
    return [E.get((p, 0, 0), -1) for p in pts]


def maxlog(C, E, bound):
    return max(k for z, k in E.items() if C.val(z) <= bound)


def h1(C):
    print("H1  the class E_0^(1/2)")
    E = E0_half(C)
    sums = all(E.get(add(a, b), -1) >= 0 for a in E for b in E if C.ok(add(a, b)))
    halves = sorted(C.val(z) for z in E)
    check("H1a E_0^(1/2) = {2 + j/2} below the top, closed under sums and +1",
          halves == halfpts(2, C.top) and sums, str([str(x) for x in halves[:6]]))
    check("H1b min Re = 2 > 3/2 + 2 gamma_Ups", min(halves) > Fr(3, 2) + 2 * C.g)
    bad = close(C, {(Fr(5, 2), 0, 0): 0})
    sums_bad = all(bad.get(add(a, b), -1) >= 0 for a in bad for b in bad if C.ok(add(a, b)))
    check("H1c control: (5/2, 0) + N_0 alone is not closed under sums (5 missing)", not sums_bad)


def h2(C, M=8):
    print("H2  the record's construction, M rounds")
    pts = halfpts(2, 5)
    rows = {}
    for name, E0 in (("int", E0_int(C)), ("half", E0_half(C))):
        E = least_def31(C, E0)
        rows[name] = [(0, logs_at(E, pts), maxlog(C, E, 5), E)]
        for m in range(1, M + 1):
            E = least_def31(C, ext_union(E0, E))
            rows[name].append((m, logs_at(E, pts), maxlog(C, E, 5), E))
    print("     points:", [str(p) for p in pts])
    for m in range(M + 1):
        print(f"     M={m}: int {rows['int'][m][1]} max<=5: {rows['int'][m][2]} | "
              f"half {rows['half'][m][1]} max<=5: {rows['half'][m][2]}")
    samepi = all(set(rows['int'][m][3]) == set(rows['half'][m][3]) for m in range(M + 1))
    check("H2a pi_1 E^(M) is the same set for both seeds at every M <= 8 (below the top)", samepi)
    ints = [i for i, p in enumerate(pts) if p.denominator == 1]
    hs = [i for i, p in enumerate(pts) if p.denominator == 2]
    same_int = all(rows['int'][m][1][i] == rows['half'][m][1][i] for m in range(M + 1) for i in ints)
    up_half = all(rows['half'][m][1][i] > rows['int'][m][1][i] for m in range(1, M + 1) for i in hs)
    check("H2b record's construction: integer points equal, every half-integer point strictly higher (M >= 1)",
          same_int and up_half)
    gap = sorted({rows['half'][m][1][i] - rows['int'][m][1][i] for m in range(1, M + 1) for i in hs})
    print("     half minus int at the half-integers, M = 1..8:", gap)
    lstar = [(rows['int'][m][2], rows['half'][m][2]) for m in range(M + 1)]
    check("H2c the largest log order at real part <= 5 is the same for both seeds at every M",
          all(a == b for a, b in lstar), str(lstar))
    for m in range(M + 1):
        for nm in ('int', 'half'):
            E = rows[nm][m][3]
            T = tot(C, E)
            ok = subset(sum_minus1(C, T, T), E) and min(C.val(z) for z in E) > Fr(3, 2) + 2 * C.g
            if not ok:
                check(f"H2d Definition 3.1 at M={m} {nm}", False)
                return rows
    check("H2d every E^(M) satisfies III.C Definition 3.1 (2)-(3)", True)
    return rows


def h3(C):
    print("H3  the sharp index set G = E_0 u-bar F(G)")
    out = {}
    for name, E0 in (("int", E0_int(C)), ("half", E0_half(C))):
        G = sharp(C, E0)
        Gr = sharp_recursive(C, E0)
        T = tot(C, G)
        d31 = subset(sum_minus1(C, T, T), G) and min(C.val(z) for z in G) > Fr(3, 2) + 2 * C.g
        fix = ext_union(E0, F_of(C, G))
        check(f"H3a {name}: G satisfies Definition 3.1 (2)-(3), contains E_0, equals E_0 u-bar F(G)",
              d31 and subset(E0, G) and close(C, fix) == G)
        check(f"H3b {name}: fixed-point iteration = recursion on the real part", G == Gr)
        coarse = close(C, ext_union(E0, G))
        check(f"H3c {name} control: G does not contain E_0 u-bar G (the coarse round grows)", not subset(coarse, G))
        out[name] = G
    return out


def h4(C, G):
    print("H4  the log orders of G")
    pts = halfpts(2, 11 * HALF)
    li, lh = logs_at(G['int'], pts), logs_at(G['half'], pts)
    print("     points:", [str(p) for p in pts])
    print("     int :", li)
    print("     half:", lh)
    fi = all(li[i] == 2 * int(p) - 3 for i, p in enumerate(pts))
    fh = all(lh[i] == int(2 * p) - 3 for i, p in enumerate(pts))
    check("H4a int: k(n) = k(n + 1/2) = 2n - 3; half: k(2 + j/2) = j + 1", fi and fh)
    off = [z for z in set(G['int']) | set(G['half']) if (z[1], z[2]) != (0, 0)]
    same_off = all(G['int'].get(z, -1) == G['half'].get(z, -1) for z in off)
    same_int = all(li[i] == lh[i] for i, p in enumerate(pts) if p.denominator == 1)
    plus1 = all(lh[i] == li[i] + 1 for i, p in enumerate(pts) if p.denominator == 2)
    check("H4b off (1/2)Z and at the integers the two G agree; at each half-integer half = int + 1",
          same_off and same_int and plus1, f"{len(off)} exponents off (1/2)Z")
    mi, mh = maxlog(C, G['int'], 5), maxlog(C, G['half'], 5)
    check("H4c the largest log order at real part <= 5 is 7 for both", mi == mh == 7, f"{mi}, {mh}")
    check("H4d control: 'the half-integer log orders are unchanged' fails",
          not all(li[i] == lh[i] for i, p in enumerate(pts) if p.denominator == 2))
    print("     pi_1 equal:", set(G['int']) == set(G['half']))
    check("H4e pi_1 G is the same for both seeds", set(G['int']) == set(G['half']))


def chain(C, E, lI, step1=True):
    left = sorted((C.val(z), z) for z in E if C.val(z) <= lI)
    J, logs = 0, 0
    while left:
        mu = left[0][0]
        win = [z for v, z in left if v < mu + 1]
        J += 1
        logs += max(E[z] for z in win)
        left = [(v, z) for v, z in left if v >= mu + 1]
    return J, logs, int(step1) + J + logs


def h5(C, G, rows):
    print("H5  LOSS-D's one-off count, 1 + J + L applications of L_b below l_I")
    grid = [Fr(3) + Fr(k, 200) for k in range(1, 100)]
    res = {}
    cands = {"int sharp": G['int'], "half sharp": G['half'], "int record M=4": rows['int'][4][3],
             "half record M=4": rows['half'][4][3], "int record M=8": rows['int'][8][3],
             "half record M=8": rows['half'][8][3]}
    for nm, E in cands.items():
        vals = {C.val(z) for z in E}
        res[nm] = sorted({chain(C, E, l) for l in grid if l not in vals})
        print(f"     {nm}: (J, L, applications) = {res[nm]}")
    check("H5a sharp: the half class adds one log step below l_I in (3, 7/2): (2, 4, 7) -> (2, 5, 8), loss 14 -> 16",
          res["int sharp"] == [(2, 4, 7)] and res["half sharp"] == [(2, 5, 8)])
    E = least_def31(C, {})
    vals = {C.val(z) for z in E}
    ctl = sorted({chain(C, E, l) for l in grid if l not in vals})
    check("H5b control: the log-free least E^C_I (empty seed) gives LOSS-D Q2's (2, 0, 3)", ctl == [(2, 0, 3)],
          str(ctl))
    return res


