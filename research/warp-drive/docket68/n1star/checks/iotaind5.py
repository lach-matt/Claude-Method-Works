def tower(tau, e, C0, K, C1=None, all_types=False):
    """the 1-form tower (D4 (1.3)): omega-breve^j of degree e - j with correction exponents C_j (absolute), by Lemma 2.1
    with the source -A_1 omega^(j-1) - A_2 omega^(j-2): A-bar_1 (homogeneous, rho^1: exponent - 1 after rho^-2),
    Q_b (rho^3: + 1), A_2 (rho^2 C^oo: + 0); returns [(degree, corrections)]"""
    e = e if isinstance(e, tuple) else X(e)
    T = [(e, C0)]
    if C1 is not None:
        T.append((add(e, X(-1)), C1))
    while len(T) <= K:
        j = len(T)
        dj = add(e, X(-j))
        dprev, Cprev = T[j - 1]
        src = {add(c, X(-1)) for c in Cprev} | shifts({add(dprev, X(1))}) | shifts({add(c, X(1)) for c in Cprev})
        if j >= 2:
            dpp, Cpp = T[j - 2]
            src |= shifts({dpp}) | shifts(Cpp)
        T.append((dj, lemma21(dj, src, tau, all_types)))
    return T


def h_terms(T, lead_vanishes=()):
    """h-breve^j = delta-hat*(0) omega-breve^j + dt (x)_s omega-breve^(j-1) (D4 (1.4)); chain degree deg_j + 1; the
    exponents: corrections + 1, omega-breve^(j-1)'s corrections, the deviation of delta* (rho^3: chain degree + 2), and
    the leading term unless it vanishes (j in lead_vanishes: the s1, v1 terms whose model part is 0)"""
    out = []
    for j, (dj, Cj) in enumerate(T):
        chain = add(dj, X(1))
        ex = {add(c, X(1)) for c in Cj} | shifts({add(chain, X(2))})
        if j >= 1:
            ex |= T[j - 1][1]
        if j not in lead_vanishes:
            ex.add(chain)
        out.append((j, chain, ex))
    return out


def offsets_of(terms):
    """iota+ offsets: every exponent minus its term's chain degree"""
    return {add(e, neg(chain)) for _, chain, ex in terms for e in ex}


