import sympy as sp, pickle, time
t0=time.time()
v,r,th,mu=sp.symbols('v r theta mu',positive=True)
out=pickle.load(open('hsolve2.pkl','rb'))
Phi=sp.Function('Phi')(v)
p1,p2=sp.Function('p1')(th),sp.Function('p2')(th)
Cf=sp.Function('C')(r,th); Af=sp.Function('A')(r,th)
cp,c2=sp.Function('cp')(th),sp.Function('c2')(th)
L=sp.Function('L')(v,th)
# r-theta: particular c_p r^(7/2) + homogeneous c2 r^2 (c2 free, fixed later)
Ert=sp.numer(sp.together(out[(1,2)]))
Eh=sp.simplify(Ert.subs(Cf,cp*r**sp.Rational(7,2)).doit()/Phi)
cpsol=sp.solve(sp.expand(Eh),cp)[0]; cpsol=sp.simplify(cpsol)
print('cp =',cpsol, round(time.time()-t0,1))
chk=sp.simplify(Ert.subs(Cf,c2*r**2).doit()); print('r^2 homogeneous residual',chk)
chk6=sp.simplify(Ert.subs(Cf,c2*r**6).doit()); print('r^6 homogeneous residual',chk6)
pickle.dump(dict(cp=cpsol),open('hsolve3.pkl','wb'))
