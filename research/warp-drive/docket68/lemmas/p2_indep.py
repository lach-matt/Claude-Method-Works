def _room_ops():
    num = np.array([[0, 0], [0, 1.0]]); sp_ = np.array([[0, 1.0], [0, 0]])
    return num, sp_


def h_room(c, n=3):
    """position c's law on a room of n charge-carrying modes: on-site energy, hopping and interaction, each set by c"""
    num, s_ = _room_ops()
    eps_, J, V = c
    H = sum(eps_*op_on(n, q, num) for q in range(n))
    for q in range(n - 1):
        hop = op_on(n, q, s_.T) @ op_on(n, q + 1, s_)
        H = H + J*(hop + hop.conj().T) + V*op_on(n, q, num) @ op_on(n, q + 1, num)
    return H


def _expm_h(H, t):
    w, v = np.linalg.eigh(H)
    return (v*np.exp(-1j*w*t)) @ v.conj().T


def _instant(psi_AR):
    """509's process (I2's swaps, chosen by r alone) on room + reference, the dump cold and the reservoir full"""
    dump0 = np.zeros(8); dump0[0] = 1
    res0 = np.zeros(8); res0[7] = 1
    st = np.einsum("ar,d,s->adsr", psi_AR, dump0, res0).reshape((2,)*12)
    for a, d_ in zip(range(3), range(3, 6)):                # the same swaps as I2's unitary, applied to the state
        st = np.swapaxes(st, a, d_)
    for k, (a, rr) in enumerate(zip(range(3), range(6, 9))):
        if (1, 0, 1)[k]:
            st = np.swapaxes(st, a, rr)
    return st.reshape(8, 8, 8, 8)                           # (A, D, R, Ref)


def _S(rho):
    w = np.linalg.eigvalsh(rho); w = w[w > 1e-14]
    return float(-(w*np.log2(w)).sum())


