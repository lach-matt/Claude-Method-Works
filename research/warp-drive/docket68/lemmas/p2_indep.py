def kron(*ops):
    out = np.array([[1.0 + 0j]])
    for o in ops:
        out = np.kron(out, o)
    return out


def op_on(n, k, o):
    return kron(*[o if q == k else np.eye(2) for q in range(n)])


def swap_q(n, a, b):
    """the swap of qubits a and b in an n-qubit register"""
    D = 2**n
    U = np.zeros((D, D))
    for x in range(D):
        bits = [(x >> (n - 1 - q)) & 1 for q in range(n)]
        bits[a], bits[b] = bits[b], bits[a]
        y = sum(bt << (n - 1 - q) for q, bt in enumerate(bits))
        U[y, x] = 1
    return U


