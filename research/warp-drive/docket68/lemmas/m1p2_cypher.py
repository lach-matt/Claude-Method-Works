def chain():
    cc = mod("cc")
    R = list(cc.ROWS)
    if not MUT.get("h2t_unsplit"):
        R2 = []
        for r in R:
            R2 += ([("H2tu", r[1], "M1", r[3]), ("H2tx", r[1], "M1 M1P2", r[3])] if r[0] == "H2t" else [r])
    else:
        R2 = R
    within = [r for r in R2 if r[0] not in ("E1x", "E2x", "H2tx")]
    inputs = list(cc.INPUTS)

    def tal(rows):
        target = [r for r in rows if r[1] in cc.GREEN]
        smallest = None
        for k in range(len(inputs) + 1):
            hits = [S for S in itertools.combinations(inputs, k) if all(cc.green(r, set(S)) for r in target)]
            if hits:
                smallest = hits
                break
        return {"n": len(rows), "m1": sum(cc.green(r, {"M1"}) for r in rows), "smallest": smallest}
    cy_all = _once("cc_all_%d" % len(R2), lambda: cc.cypher(*cc.index(R2)))
    cy_in = _once("cc_in_%d" % len(within), lambda: cc.cypher(*cc.index(within)))
    return {"before": tal(R), "after": tal(R2), "within": tal(within), "adds_all": cy_all["adds_nothing"],
            "adds_within": cy_in["adds_nothing"]}


