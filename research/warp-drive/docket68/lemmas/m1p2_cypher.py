def codings():
    """universe (nominal) in both orders x the unknown placed low, high, or between 0 and 1"""
    return [(uo, up) for uo in ((0, 1), (1, 0)) for up in ("low", "high", "mid")]


def ask(cs, coding, k=2):
    """per language: the decoded admitted cells (tuples over C), or None if silent"""
    cy = mod("cy")
    uo, up = coding
    present = [{c[i] for c in cs} for i in range(len(C))]
    vo = {}
    for i, name in enumerate(C):
        base = [v for v in (list(uo) if name == "universe" else [0, 1]) if v in present[i]]
        if U in present[i]:
            base = [U] + base if up == "low" else (base + [U] if up == "high" else base[:1] + [U] + base[1:])
        vo[name] = base
    ix = cy.Index("m1p2", C, [list(c) for c in cs], value_order=vo)
    inv = [{v: k_ for k_, v in ix.code[i].items()} for i in range(len(C))]
    res = {}
    for lang in LANGS:
        out, _ = cy.ADMISSION[lang][0](ix, {"statistics_order": k})
        res[lang] = None if out is None else {tuple(inv[i][c[i]] for i in range(len(C))) for c in out}
    return res


