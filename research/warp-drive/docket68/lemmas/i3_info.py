def life_law():
    """I1: E^2 linear in t, S as (1 - t/tau)^(3/4), |dr_h/dt| = r_h/(4 tau(t))"""
    t, k, a, E0, r = sp.symbols("t k a E0 r", positive=True)
    T = 1 / (2 * sp.pi * r)
    E_r = a * r ** 2 if not MUT.get("eofr") else a * r       # the mutant: the four-dimensional E ~ r
    expo = lambda P_r: sp.simplify(sp.log(P_r.subs(r, 2) / P_r.subs(r, 1)) / sp.log(E_r.subs(r, 2) / E_r.subs(r, 1)))
    p_exp = expo(r ** 2 * T ** 4)                                # the plane's channel
    p_bulk = expo(r ** 3 * T ** 5)                               # the bulk's channel
    E = sp.Function("E")
    sol = sp.dsolve(sp.Eq(E(t).diff(t), -k * E(t) ** p_exp), E(t), ics={E(0): E0})
    sol = sol if not isinstance(sol, list) else [s for s in sol if s.rhs.subs(t, 0) == E0][0]
    tau = E0 / (2 * k / E0)
    lin = sp.simplify(sol.rhs ** 2 - E0 ** 2 * (1 - t / tau)) == 0
    s_exp = sp.Rational(3, 2)                                    # S ~ r^3 ~ E^(3/2)
    rh = sp.sqrt(sol.rhs / a)
    drdt = sp.diff(rh, t)
    tau_left = sol.rhs / (2 * k / sol.rhs)
    rate = sp.simplify(-drdt - rh / (4 * tau_left)) == 0
    return dict(p_exp=p_exp, p_bulk=p_bulk, linear=lin, s_exp=s_exp, rate=rate)


