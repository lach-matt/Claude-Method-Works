    for carrier in ("G", "hbar, alpha fixed", "hbar, e fixed", "c"):
        for sig in ("SI", "Planck"):
            for L2 in (2, 4):
                c = candidate(carrier, sig, L2)
                shares_si = c["x"]["hbar"] == 0 and c["x"]["c"] == 0 and c["x"]["e2"] == 0
                matter = c["alpha"] == 0 and c["a0"] == 0
                if MUT.get("hbar_alpha_fixed_counted") and carrier == "hbar, alpha fixed":
                    shares_si, matter = True, True            # dimensionless matter ours, the SI re-realised
                # 225 A's full coordinates, as factors
                me = (round(_f(L2, c["sigma"]), 12), round(_f(L2, c["offset"]), 12), round(_f(L2, c["k4"]), 12), matter)
                b2 = (1.0, 1.0, 2.0, True)
                sep = me != b2
                planck_me = (round(_f(L2, c["sigma_planck"]), 12), round(_f(L2, c["alphaG"]), 12),
                             round(_f(L2, c["alpha"]), 12))
