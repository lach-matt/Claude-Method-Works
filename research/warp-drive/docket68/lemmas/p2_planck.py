# ------------------------------------------------------------------------------------------- 1. which universe is 2P
# Every candidate scales l_P by lam (lam^2 = L2).  Changes are exponents of lam (exact Fractions); the factor of a
# quantity is L2 ** (exponent / 2).  hbar, G, c: what carries l_P = sqrt(hbar G / c^3); e: fixed, or with e^2 ~ hbar
# (alpha fixed).  sigma and the offset: held in SI, or scaled as sigma_P (Planck units ours).
def candidate(carrier, sig, L2):
    x = {"G": F(0), "hbar": F(0), "c": F(0), "e2": F(0)}
    if carrier == "G":
        x["G"] = F(2)
    elif carrier == "hbar, alpha fixed":
        x["hbar"], x["e2"] = F(2), F(2)
    elif carrier == "hbar, e fixed":
        x["hbar"] = F(2)
    elif carrier == "c":
        x["c"] = F(-2, 3)
    lP = (x["hbar"] + x["G"] - 3 * x["c"]) / 2                    # must be 1
    alpha = x["e2"] - x["hbar"] - x["c"]
    a0 = x["hbar"] - x["c"] - alpha                               # hbar/(m_e c alpha), m_e fixed
    sigP = 7 * x["c"] - x["hbar"] - 2 * x["G"]
    sigma = sigP if sig == "Planck" else F(0)
    k4 = x["G"] - sigma + 4 * x["c"] * 0                          # 48 pi G = kappa5^4 sigma (c's carried at fixed c)
    if carrier == "c":
        k4 = x["G"] - sigma - 4 * x["c"]                          # G = kappa5^4 sigma c^4 / (48 pi): kappa5^4 ~ G/(sigma c^4)
    ell2 = 4 * x["c"] - x["G"] - sigma                            # ell^2 = 3c^4 / (4 pi G sigma)
    alphaG = x["G"] - x["hbar"] - x["c"]                          # G m_p^2 / (hbar c)
    return dict(carrier=carrier, sig=sig, L2=L2, x=x, lP=lP, alpha=alpha, a0=a0, sigma=sigma, offset=sigma, sigP=sigP,
                k4=k4, ell2=ell2, alphaG=alphaG, sigma_planck=sigma - sigP, offset_planck=sigma - sigP,
                ell_planck=(ell2 - 2 * lP) / 2)


