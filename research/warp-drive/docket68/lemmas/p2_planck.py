def selftest():
    r = checks(compute())
    for n, ok in r:
        print("  [%s] %s" % ("ok" if ok else "FAIL", n))
    k = sum(ok for _, ok in r)
    print("selftest: %d/%d" % (k, len(r)))
    return k == len(r)


def mutants():
    global MEMBERS
    caught = 0
    base = dict(MEMBERS)
    for k, desc in MUTANTS.items():
        MUT.clear()
        MUT[k] = True
        if k == "sigma_held_si":
            MEMBERS = {kk: (v[0], v[1], F(1)) for kk, v in base.items()}
        try:
            failed = [n.split()[0] for n, ok in checks(compute()) if not ok]
        except Exception as ex:
            failed = ["raised %s" % type(ex).__name__]
        MUT.clear()
        MEMBERS = dict(base)
        caught += bool(failed)
        print("  mutant %-17s %-75s %s" % (k, desc, "caught by " + ", ".join(sorted(set(failed))) if failed else "NOT CAUGHT"))
    print("mutants: %d/%d caught" % (caught, len(MUTANTS)))
    return caught == len(MUTANTS)


