def sector(gf, sf):
    """the theorem's relations at G x gf, sigma and delta sigma x sf (SI), our sigma taken at the window's floor (every
    ratio below is independent of where sigma sits; the window membership is not, and is reported separately)"""
    Gx, sig, ds = G * gf, S0 * float(sf), PG.DSIG * float(sf)
    ell2 = 3 * C ** 4 / (4 * math.pi * Gx * (sig - 2 * ds))
    kap4 = 48 * math.pi * Gx / (sig * C ** 4)
    L4 = 8 * math.pi * Gx * ds / C ** 4
    co = PG.corridor(Gx)
    sP = co["sigma_P"]
    lP = (HBAR * Gx / C ** 3) ** 0.5
    return dict(G=Gx, sigma=sig, offset=ds, ell=ell2 ** 0.5, k4=kap4, L4=L4, L5=2 * L4 - kap4 * sig ** 2 / 6,
                E1=co["E1"], m1=co["m1"], A_bit=co["A_bit"], sigma_P=sP, N_max=sP / (8 * math.log(2) * ds), lP=lP,
                sigma_planck=sig / sP, offset_planck=ds / sP, ell_planck=ell2 ** 0.5 / lP, ell_over_m=ell2 ** 0.5 / co["m1"],
                alpha_G=Gx * PG.M_P ** 2 / (HBAR * C), share=PG.matter_shift(Gx), nstar=(PG.ASSEMBLY_MAX_J / co["E1"]) ** 2)


def window(gf, sf):
    """the member's own window: the floor from the table-top bound read against its own G (relative) or as the same
    absolute 1/r^3 force (absolute); the top from ITEM197's ell > 8.5415 m1; and the condition on OUR sigma for the
    member's sigma (our sigma x sf) to lie inside it"""
    Gx = G * gf
    kap = 3 * C ** 4 / (4 * math.pi * Gx)
    m1 = PG.corridor(Gx)["m1"]
    floor_rel = kap / PG.ELL_MAX ** 2
    floor_abs = 3 * C ** 4 / (4 * math.pi * G * PG.ELL_MAX ** 2)
    top = kap / (ELL_MIN_OVER_M1 * m1) ** 2
    return dict(floor_rel=floor_rel, floor_abs=floor_abs, top=top, need_rel=floor_rel / float(sf), need_abs=floor_abs / float(sf),
                need_top=top / float(sf))


def universe_cells():
    """item 201's coordinates over every member: SI (sigma, offset), Planck units (sigma/sigma_P, offset/sigma_P), and
    item 225 A's full coordinates (SI values, the coupling, the matter law)"""
    si, pl, full = {}, {}, {}
    for u, (law, gf, sf) in MEMBERS.items():
        sc = sector(gf, sf)
        si[u] = ("%.10g" % sc["sigma"], "%.10g" % sc["offset"])
        pl[u] = ("%.10g" % sc["sigma_planck"], "%.10g" % sc["offset_planck"])
        full[u] = si[u] + ("%.10g" % sc["k4"], law)
    grp = lambda m: sorted(sorted(u for u in m if m[u] == v) for v in set(m.values()))
    return dict(si=grp(si), planck=grp(pl), full=grp(full))


