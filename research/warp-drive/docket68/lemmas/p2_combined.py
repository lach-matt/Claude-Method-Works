def _u_elastic(x, rho0, B0, Bp):
    """BM3's stored energy per unit mass at x = V/V0 (the energy whose derivative is p2_gravity._bm3's pressure)"""
    y = x ** (-2.0 / 3.0) - 1.0
    return 9.0 * B0 / (16.0 * rho0) * (y ** 3 * Bp + y ** 2 * (6.0 - 4.0 * (y + 1.0)))


def _binding(Pc, rho0, B0, Bp, Gx, n=600):
    """the same cold hydrostatic sphere as p2_gravity._sphere (its EOS inversion imported), integrating also the
    gravitational binding W = int G m dm / r and the elastic energy U = int u(x) dm; returns (R, M, W, U)"""
    xc = PG._x_of_P(Pc, B0, Bp)
    rc = rho0 / xc
    dr = (3 * Pc / (2 * math.pi * Gx * rc ** 2)) ** 0.5 / n
    st = {"x": xc}

    def f(r, P, m):
        st["x"] = PG._x_of_P(P, B0, Bp, st["x"])
        rho = rho0 / st["x"]
        dm = 4 * math.pi * r ** 2 * rho
        return -Gx * m * rho / r ** 2, dm, Gx * m * dm / r, _u_elastic(st["x"], rho0, B0, Bp) * dm
    m0 = 4.0 / 3.0 * math.pi * dr ** 3 * rc
    r, P, m, W, U = dr, Pc, m0, 3.0 / 5.0 * Gx * m0 ** 2 / dr, _u_elastic(xc, rho0, B0, Bp) * m0
    while True:
        k1 = f(r, P, m)
        k2 = f(r + dr / 2, P + dr / 2 * k1[0], m + dr / 2 * k1[1])
        k3 = f(r + dr / 2, P + dr / 2 * k2[0], m + dr / 2 * k2[1])
        k4 = f(r + dr, P + dr * k3[0], m + dr * k3[1])
        d = [dr / 6 * (k1[i] + 2 * k2[i] + 2 * k3[i] + k4[i]) for i in range(4)]
        if P + d[0] <= 0:
            t = P / -d[0]
            return r + t * dr, m + t * d[1], W + t * d[2], U + t * d[3]
        r, P, m, W, U = r + dr, P + d[0], m + d[1], W + d[2], U + d[3]


