def interactions(bd):
    """for each 2c member: X_2c / X_ours against (X_2a / X_ours)(X_2b / X_ours) -- the product is what two laws acting
    independently would give; the interaction is the departure from it"""
    out = {}
    for el in METALS:
        o = bd[(el, "ours")]
        for law in ("min", "mirror"):
            a, b, c = bd[(el, "2a-" + law)], bd[(el, "2b")], bd[(el, "2c-" + law)]
            row = {}
            for k in ("g", "R", "rho_mean", "Pc", "W_frac"):
                ra, rb, rc = a[k] / o[k], b[k] / o[k], c[k] / o[k]
                if MUT.get("additive_combination"):                  # changes added, not compounded
                    prod = 1 + (ra - 1) + (rb - 1)
                else:
                    prod = ra * rb
                row[k] = dict(r2a=ra, r2b=rb, r2c=rc, product=prod, interaction=rc / prod - 1)
            row["dB0"] = a["B0"] / o["B0"] - 1
            out[(el, law)] = row
    return out


def compression(bd, inter):
    """the interaction as a change of compression: 2b's extra pull beyond x2, t = g2b/gours - 2, read as t = k Pc/B0 with
    k fitted per metal from ours and 2b alone; then 2c's t is k (Pc/B0) of 2a's metal, and the predicted interaction is
    (k (Pc/B0)_2a - t_ours) / (2 + t_ours)"""
    out = {}
    for el in METALS:
        o, b = bd[(el, "ours")], bd[(el, "2b")]
        t0 = b["g"] / o["g"] - 2
        c0 = o["Pc"] / o["B0"]
        k = t0 / c0
        for law in ("min", "mirror"):
            a = bd[(el, "2a-" + law)]
            ca = a["Pc"] / a["B0"]
            out[(el, law)] = dict(k=k, comp_ours=c0, comp_2a=ca, d_comp=ca - c0, pred=(k * ca - t0) / (2 + t0),
                                  actual=inter[(el, law)]["g"]["interaction"])
    return out


