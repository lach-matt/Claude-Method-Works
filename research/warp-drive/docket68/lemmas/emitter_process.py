    rng = np.random.default_rng(4961)
    q = rng.normal(size=(300, 4)); q /= np.linalg.norm(q, axis=1)[:, None]
    v = rng.normal(size=(300, 4)); v -= (v * q).sum(1)[:, None] * q
    cj = np.array([1, -1, -1, -1])

    def hh(q, v, e2b):
        sg = _qmul(q * cj, v)[:, 1:]
        return e2b * (sg[:, 0] ** 2 + sg[:, 1] ** 2) + e2b ** -2 * sg[:, 2] ** 2

    def defect(n, e2b):
        n = n / np.linalg.norm(n)
        Rf = lambda x: x - 2 * (x @ n)[:, None] * n
        h0 = hh(q, v, e2b)
