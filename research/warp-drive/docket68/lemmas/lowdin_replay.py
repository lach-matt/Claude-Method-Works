#!/usr/bin/env python3
"""lowdin_replay.py -- rebuild the Löwdin chain's runtime (M's s40 self-driving walk, nlchain.py, on the ruling field
hfc2/t7b_hf/t7c_hfsr/t7c_kernel with the s48 guard nlguard.py) from the chat export, for item 219.  2026-10-11.

M (item 219 follow-up): "That and all the lowdin Handoff and chat transcipts are all in the repo".  The sealed archive
LOWDIN-HANDOFF-103.tgz is not a file here; its runtime is recoverable from the 106 Löwdin chats (drive/chats, read-only),
because every module was written there.  recovered/ holds only the FIRST write of most modules (t7b_hf.py, rad.py,
nlchain.py, ...), and later sessions patched them by python heredoc, sed -i, str_replace and cp, so recovered/ alone does
not run (rad.py's shooting node count fails at Z = 21 1s).  This file replays, in chronological order and keyed by
basename, the file operations its patterns recognise (create_file, str_replace, cat heredocs, python heredoc patches,
sed -i and sed redirects with quote-aware statement splitting, two-file cp/mv) in the 106 Löwdin-titled chats, skipping
every tool call the tool refused (tool_result is_error), and writes the tracked modules to OUTDIR.

Five decisions, each stated, each checked:
  1. Refused tool calls are not replayed.  One of them matters: LCP16:5:16, a create_file of a 94-line t7b_hf.py that
     the tool refused ("File already exists"); applied, it leaves no HF class.  Checked: t7b_hf.py after session 28's
     patch reproduces the sha256 the chat printed for rt/t7b_hf.py, a53d8a1c3936d437...
  2. shoot_sr.c, which is not otherwise tracked, is generated by the exact sed command of LCP15 3/27 from the replayed
     shoot.c.
  3. ground.py is a shim that imports the seated member method/members/LW1-ground.py by path (never a copy); the
     record's runtime ground.py is that member plus one trailing newline (sha256 6219f381..., 6473 B).
  4. t7c_cuaudit.py is a stub whose every attribute raises: hfc2 imports it for the correlation potential, which nlchain
     switches off (hfc2.CORR = False).  nlguard turns any exception into a failed channel, so completion alone does not
     show the stub untouched; every failure reason in the run logs is a node-count RuntimeError, none names the stub.
  5. The three C kernels are compiled with -include stdlib.h, a guard only: the replayed shoot.c already carries the
     include (the record's own sed at LCP3 9:9) and shoot_x.c calls no malloc.
Checked end to end against the record: the rebuilt step reproduces the chats' rows exactly -- Sc (21) 3d D -0.26664 margin
0.09763 (LCP39), Ac (89) 6d -0.15762 margin 0.03233 and Th (90) 6d -0.19094 margin 0.05405 (LCP47), and Th's top three
channels at c = 137.035999 (6d -0.19094, 5f -0.13689, 7p -0.13206) and at c = 1e6 (5f -0.39017, 6d -0.26099,
7p -0.14042; LCP52, after the record's own fault F54.2) -- see madelung_field.py.

Read-only on the repository; writes only OUTDIR (give a scratch path).  Stdlib (the runtime itself needs numpy, scipy, gcc).
usage: python3 lowdin_replay.py OUTDIR [--check]       (--check: print the module sha256s and the anchor verdict)
       python3 lowdin_replay.py --selftest | --mutants   (fast: checks the decisions against the shards, no replay)
"""
import csv
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(HERE))))
TRACK = {"derive_P.py", "eigen_fix.py", "hfc2.py", "hfs.py", "nlchain.py", "nlguard.py", "rad.py", "shoot.c", "shoot_x.c",
         "step2_run.py", "t5_scf.py", "t7b_hf.py", "t7c_hfsr.py", "t7c_kernel.py", "tfd.py"}
SKIP = set()          # refused tool calls are skipped by rule (tool_result is_error); none by hand
ANCHOR = ("t7b_hf.py", "a53d8a1c3936d437589f15e676fdcfb89fd4e18f1a4baf68e583aaff66f031e7")   # LCP26 msg 16, rt/t7b_hf.py
SHOOT_SR_SED = ("sed 's/int shoot(const double \\*q, int n, double h, int l, double \\*ylast)/int shoot_s(const double *q, "
                "int n, double h, double slope, double *ylast)/; s/exp((l+0.5)\\*h)/exp(slope*h)/' shoot.c > shoot_sr.c")
GROUND_SHIM = ('# shim: imports the seated member method/members/LW1-ground.py by path (never a copy)\n'
               'import importlib.util as _u, os as _o\n'
               '_s = _u.spec_from_file_location("lw1_ground", %r)\n'
               '_m = _u.module_from_spec(_s); _s.loader.exec_module(_m)\n'
               'globals().update({k: v for k, v in vars(_m).items() if not k.startswith("__")})\n')
CUAUDIT_STUB = ('# stub: hfc2 imports the correlation module; nlchain sets hfc2.CORR = False, so any use raises\n'
                'def __getattr__(name):\n    raise AttributeError("t7c_cuaudit stub: %s used" % name)\n')
FNAME = re.compile(r"[\w.\-]+\.(?:py|c|json|jsonl|txt|md|tsv|sh)\b")


def lowdin_chats():
    """(created_at, title, shard) for every Löwdin chat, oldest first"""
    rows = list(csv.reader(open(os.path.join(REPO, "drive", "chats", "INDEX.tsv"), encoding="utf-8"), delimiter="\t"))
    out = [(r[3], r[2], r[0]) for r in rows[1:] if r[2].startswith("LCP") or "lowdin" in r[2].casefold()
           or "löwdin" in r[2].casefold()]
    return sorted(out)


def replay(outdir, track=TRACK, skip=SKIP):
    fs, log = {}, []
    bn = lambda p: os.path.basename(p.strip().strip("'\""))
    work = tempfile.mkdtemp(prefix="lowdin_replay_")

    def sandbox(cmd, names, where, kind):
        d = tempfile.mkdtemp(dir=work)
        try:
            for n in names:
                if n in fs:
                    open(os.path.join(d, n), "w").write(fs[n])
            before = {n: fs.get(n) for n in names}
            r = subprocess.run(["bash", "-c", cmd], cwd=d, capture_output=True, text=True, timeout=120)
            changed = []
            for n in sorted(os.listdir(d)):
                p = os.path.join(d, n)
                if n in track and os.path.isfile(p):
                    t = open(p).read()
                    if t != before.get(n):
                        fs[n] = t
                        changed.append(n)
            log.append(where + (kind, ",".join(changed) or "-", r.returncode))
        except subprocess.TimeoutExpired:
            log.append(where + (kind, "TIMEOUT", -1))
        finally:
            shutil.rmtree(d, ignore_errors=True)

    def unquoted_parts(st):
        """split a statement into (text, quoted?) runs, honouring '...' and "..." """
        parts, buf, q = [], "", None
        for ch in st:
            if q:
                buf += ch
                if ch == q:
                    parts.append((buf, True)); buf, q = "", None
            elif ch in "'\"":
                if buf: parts.append((buf, False))
                buf, q = ch, ch
            else:
                buf += ch
        if buf: parts.append((buf, bool(q)))
        return parts

    def strip_paths(st):
        """make a statement run in the sandbox: drop a leading cd, strip directory prefixes from unquoted file operands
        only -- a sed script's quoted text is left exactly as the record wrote it"""
        st = re.sub(r"^\s*cd\s+\S+\s*$", "true", st)
        return "".join(t if qd else re.sub(r"(?<![\w.])(?:/[\w.\-]+|\.\.?|[\w\-]+)(?:/[\w.\-{},]+)*/([\w.\-]+\.(?:py|c|json|jsonl|txt|md|tsv|sh))",
                                         r"\1", t) for t, qd in unquoted_parts(st))

    def statements(cmd):
        """split on && ; || and newlines outside quotes"""
        out, buf, q, i = [], "", None, 0
        while i < len(cmd):
            ch = cmd[i]
            if q:
                buf += ch
                if ch == q: q = None
            elif ch in "'\"":
                q = ch; buf += ch
            elif cmd.startswith("&&", i) or cmd.startswith("||", i):
                out.append(buf); buf = ""; i += 2; continue
            elif ch in ";\n":
                out.append(buf); buf = ""
            else:
                buf += ch
            i += 1
        out.append(buf)
        return out

    def bash(cmd, where):
        for m in re.finditer(r"cat\s*>\s*([^\s<]+)\s*<<\s*-?['\"]?(\w+)['\"]?[^\n]*\n(.*?)\n\2\b", cmd, re.S):
            n = bn(m.group(1))
            if n in track or n.endswith(".py"):
                fs[n] = m.group(3) + "\n"
                if n in track:
                    log.append(where + ("HEREDOC", n, 0))
        for m in re.finditer(r"python3?\s+-\s*<<\s*['\"]?(\w+)['\"]?[^\n]*\n(.*?)\n\1\b", cmd, re.S):
            body = m.group(2)
            if any(n in track for n in FNAME.findall(body)) and re.search(r"open\([^)]*['\"]w['\"]|\.write_text\(", body):
                body2 = re.sub(r"(['\"])(?:/[\w.\-]+)+/([\w.\-]+\.(?:py|c|json|jsonl|txt|md))\1", r"\1\2\1", body)
                sandbox("python3 - <<'PYEOF'\n" + body2 + "\nPYEOF", set(FNAME.findall(body)), where, "PYPATCH")
        outside = re.sub(r"<<\s*-?['\"]?(\w+)['\"]?[^\n]*\n.*?\n\1\b", "", cmd, flags=re.S)
        for stmt in statements(outside):
            st = stmt.strip()
            names = set(FNAME.findall(st))
            if re.match(r"sed\s+(-\w*\s+)*-i", st) and names & track:
                sandbox(strip_paths(st), names, where, "SED-I")
            elif re.match(r"sed\s", st) and re.search(r">\s*\S+", st):
                tgt = bn(re.search(r">\s*(\S+)", st).group(1))
                if tgt in track:
                    sandbox(strip_paths(st), names | {tgt}, where, "SED>")
            elif re.match(r"(cp|mv)\s", st):
                toks = [t for t in st.split()[1:] if not t.startswith("-")]
                if len(toks) == 2 and FNAME.fullmatch(bn(toks[0])) and FNAME.fullmatch(bn(toks[1])):
                    a, b = bn(toks[0]), bn(toks[1])
                    if a != b and b in track and a in fs:
                        fs[b] = fs[a]
                        log.append(where + ("CP", a + "->" + b, 0))

    for _, title, shard in lowdin_chats():
        d = json.load(open(os.path.join(REPO, "drive", "chats", shard), encoding="utf-8"))
        refused = {b.get("tool_use_id") for m in (d.get("chat_messages") or []) for b in (m.get("content") or [])
                   if b.get("type") == "tool_result" and b.get("is_error")}
        for i, m in enumerate(d.get("chat_messages") or []):
            for j, b in enumerate(m.get("content") or []):
                if b.get("type") != "tool_use":
                    continue
                where = (title, i, j)
                if b.get("id") in refused or "%s:%d:%d" % where in skip:
                    log.append(where + ("REFUSED", "-", 0))
                    continue
                inp = b.get("input") or {}
                path = inp.get("path", "")
                if path and "file_text" in inp:
                    fs[bn(path)] = inp["file_text"]
                    if bn(path) in track:
                        log.append(where + ("WRITE", bn(path), 0))
                elif path and "old_str" in inp and bn(path) in fs and bn(path) in track:
                    k = fs[bn(path)].count(inp["old_str"])
                    if k == 1:
                        fs[bn(path)] = fs[bn(path)].replace(inp["old_str"], inp.get("new_str", ""))
                    log.append(where + ("STR_REPLACE", bn(path), 0 if k == 1 else 9))
                elif inp.get("command"):
                    c = inp["command"]
                    bash(" ".join(map(str, c)) if isinstance(c, list) else c, where)
    shutil.rmtree(work, ignore_errors=True)
    os.makedirs(outdir, exist_ok=True)
    for n in sorted(track):
        if n in fs:
            open(os.path.join(outdir, n), "w").write(fs[n])
    subprocess.run(["bash", "-c", SHOOT_SR_SED], cwd=outdir, check=True)
    open(os.path.join(outdir, "ground.py"), "w").write(GROUND_SHIM % os.path.join(REPO, "method", "members", "LW1-ground.py"))
    open(os.path.join(outdir, "t7c_cuaudit.py"), "w").write(CUAUDIT_STUB)
    for x in ("shoot", "shoot_x", "shoot_sr"):
        subprocess.run(["gcc", "-O2", "-shared", "-fPIC", "-include", "stdlib.h", "-o", "lib%s.so" % x, x + ".c", "-lm"],
                       cwd=outdir, check=True)
    with open(os.path.join(outdir, "REPLAY-LOG.tsv"), "w") as f:
        for r in log:
            f.write("\t".join(map(str, r)) + "\n")
    sha = {n: hashlib.sha256(open(os.path.join(outdir, n), "rb").read()).hexdigest()
           for n in sorted(track | {"shoot_sr.c"}) if os.path.exists(os.path.join(outdir, n))}
    return sha, log


MUT = {}


def _shard(title):
    sh = {t: s for _, t, s in lowdin_chats()}
    return json.load(open(os.path.join(REPO, "drive", "chats", sh[title]), encoding="utf-8"))


def checks():
    res = []
    add = lambda n, ok: res.append((n, bool(ok)))
    chats = lowdin_chats()
    add("R1 the Löwdin chats in the export: 106 (LCP2-LCP101, five named, and 'Method Löwdin project data and code "
        "transfer')", len(chats) == 106 and sum(t.startswith("LCP") for _, t, _ in chats) == 100)
    key = (MUT.get("skip") or "LCP16:5:16").split(":")
    msg = _shard(key[0])["chat_messages"][int(key[1])]["content"]
    b = msg[int(key[2])]
    ft = (b.get("input") or {}).get("file_text", "")
    tr = [x for x in msg if x.get("type") == "tool_result" and x.get("tool_use_id") == b.get("id")]
    add("R2 the refused call that matters: LCP16:5:16 is a create_file of a 94-line t7b_hf.py without the HF class, and "
        "its tool_result is_error ('File already exists'), so the replay skips it",
        (b.get("input") or {}).get("path", "").endswith("/t7b_hf.py") and ft.count("\n") == 94 and "class HF" not in ft
        and bool(tr) and tr[0].get("is_error") is True)
    anchor = MUT.get("anchor") or ANCHOR[1]
    txt = ""
    for bb in _shard("LCP26")["chat_messages"][16]["content"]:
        if bb.get("type") == "tool_result":
            cc = bb.get("content")
            txt += " ".join(x.get("text", "") for x in cc if isinstance(x, dict)) if isinstance(cc, list) else str(cc)
    add("R3 the anchor: LCP26 message 16 prints sha256 %s... beside rt/t7b_hf.py" % anchor[:16],
        (anchor + "  rt/t7b_hf.py") in txt)
    sig = "int shoot(const double *q, int n, double h, int l, double *ylast) { y1=y0*exp((l+0.5)*h); }"
    r = subprocess.run(["bash", "-c", SHOOT_SR_SED.replace(" shoot.c > shoot_sr.c", "")], input=sig, capture_output=True,
                       text=True)
    add("R4 the shoot_sr.c sed (LCP15 3/27) turns shoot(..., int l, ...) into shoot_s(..., double slope, ...) and "
        "exp((l+0.5)*h) into exp(slope*h)", r.stdout.strip() == "int shoot_s(const double *q, int n, double h, double slope, "
        "double *ylast) { y1=y0*exp(slope*h); }")
    return res


def selftest():
    r = checks()
    for n, ok in r:
        print("  [%s] %s" % ("ok" if ok else "FAIL", n))
    print("selftest: %d/%d" % (sum(ok for _, ok in r), len(r)))
    return all(ok for _, ok in r)


def mutants():
    M = {"skip": ("skip", "LCP16:3:20", "the refused call taken to be the adopted 152-line write"),
         "anchor": ("anchor", "9fd4e18f" + ANCHOR[1][8:], "an anchor the chat never printed")}
    caught = 0
    for k, (key, val, desc) in M.items():
        MUT.clear()
        MUT[key] = val
        failed = [n.split()[0] for n, ok in checks() if not ok]
        MUT.clear()
        caught += bool(failed)
        print("  mutant %-7s %-48s %s" % (k, desc, "caught by " + ", ".join(failed) if failed else "NOT CAUGHT"))
    print("mutants: %d/%d caught" % (caught, len(M)))
    return caught == len(M)


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        sys.exit(0 if selftest() else 1)
    if "--mutants" in sys.argv:
        sys.exit(0 if mutants() else 1)
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(2)
    sha, log = replay(sys.argv[1])
    missing = sorted(TRACK - set(sha))
    print("replayed %d operations; modules %d; missing %s" % (len(log), len(sha), missing or "none"))
    if "--check" in sys.argv:
        for n, h in sha.items():
            print("  %-14s %s" % (n, h))
        ok = sha.get(ANCHOR[0]) == ANCHOR[1]
        print("anchor %s sha256 = the chat's recorded %s...: %s" % (ANCHOR[0], ANCHOR[1][:16], "MATCH" if ok else "MISMATCH"))
        sys.exit(0 if ok and not missing else 1)
