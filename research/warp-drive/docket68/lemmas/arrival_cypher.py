def selftest():
    r = checks(compute())
    for n, ok in r:
        print("  [%s] %s" % ("ok" if ok else "FAIL", n))
    k = sum(ok for _, ok in r)
    print("selftest: %d/%d" % (k, len(r)))
    return k == len(r)


def mutants():
    caught = 0
    for key, desc in MUTANTS.items():
        MUT.clear()
        MUT[key] = True
        try:
            failed = [n.split()[0] for n, ok in checks(compute()) if not ok]
        except Exception as ex:
            failed = ["raised %s" % type(ex).__name__]
        MUT.clear()
        good = bool(failed) and not any(f.startswith("raised") for f in failed)
        caught += good
        print("  mutant %-15s %-66s %s" % (key, desc, "caught by " + ", ".join(sorted(set(failed))) if failed
                                             else "NOT CAUGHT"))
    print("mutants: %d/%d caught" % (caught, len(MUTANTS)))
    return caught == len(MUTANTS)


