def _over(runs, lang, t):
    """the distinct answers (tuples of admitted target cells) over the codings"""
    return {tuple(v[lang][t]) if v[lang] is not None else None for v in runs.values()}


def _count(runs, lang, t):
    """in how many codings the language admits the target"""
    return sum(bool(v[lang] and v[lang][t]) for v in runs.values())


