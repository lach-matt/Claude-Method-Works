NATIVE = ((MIRROR, OWN), FORMS, "high")


def ask(cs, coding, langs=LANGS, k=2):
    """per language: the decoded admitted cells (tuples over C), or None if silent"""
    cy = mod("cy")
    bo, fo, up = coding
    present = [{c[i] for c in cs} for i in range(len(C))]
    vo = {}
    for i, name in enumerate(C):
        if name == "beyond":
            base = [v for v in bo if v in present[i]]
        elif name == "tension":
            base = [v for v in TENSIONS if v in present[i]]
        elif name == "form":
            base = [v for v in fo if v in present[i]]
        else:
            base = [v for v in (0, 1) if v in present[i]]
            if U in present[i]:
                base = [U] + base if up == "low" else (base + [U] if up == "high" else base[:1] + [U] + base[1:])
        vo[name] = base
    ix = cy.Index("m1x", C, [list(c) for c in cs], value_order=vo)
    inv = [{v: k_ for k_, v in ix.code[i].items()} for i in range(len(C))]
    res = {}
    for lang in langs:
        out, _ = cy.ADMISSION[lang][0](ix, {"statistics_order": k})
        res[lang] = None if out is None else {tuple(inv[i][c[i]] for i in range(len(C))) for c in out}
    return res


def picks(adm):
    """the admitted cells meeting each target, sorted"""
    if adm is None:
        return None
    return {t: sorted((h for h in adm if f(h)), key=str) for t, f in TARGETS.items()}


def sweep(named):
    """every coding: the four order-dependent languages and statistics at order 2 and 3"""
    cs = [c for _, c in named]
    runs = {}
    for co in codings():
        r = ask(cs, co, LANGS, 2)
        r["statistics3"] = ask(cs, co, ("statistics",), 3)["statistics"]
        runs[co] = {l: picks(v) for l, v in r.items()}
    return runs


def stat(named, k):
    """statistics is pairwise (order-k) marginal support: independent of every coding; run on the native one"""
    return picks(ask([c for _, c in named], NATIVE, ("statistics",), k)["statistics"])


def blocking(named, cell, k):
    """the k-subsets of coordinates on which the cell's projection is seen in no data cell"""
    cs = [c for _, c in named]
    return sorted(tuple(C[i] for i in S) for S in itertools.combinations(range(len(C)), k)
                  if tuple(cell[i] for i in S) not in {tuple(c[i] for i in S) for c in cs})


def cypher_runs(d):
    main = cells(d)
    fav = cells(d, fav=True)
    flip = cells(d, fav=True, flip=True)
    ctl_m = cells(d, coin_pos=True)
