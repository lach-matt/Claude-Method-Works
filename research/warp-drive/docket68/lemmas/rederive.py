def selftest(quiet=False):
    o = compute()
    r = checks(o)
    if not quiet:
        report(o)
        for n, ok in r:
            print("  [%s] %s" % ("ok" if ok else "FAIL", n))
        print("selftest: %d/%d" % (sum(ok for _, ok in r), len(r)))
    return all(ok for _, ok in r)


def mutants():
    names = ["dest_negative", "keep_expansion", "one_E", "no_rs"]
    caught = 0
    for m in names:
        MUT.clear(); MUT.add(m)
        try:
            bad = not selftest(quiet=True)
        except Exception:
            bad = True
        caught += bad
        print("mutant %-15s %s" % (m, "caught" if bad else "MISSED"))
    MUT.clear()
    print("%d/%d caught" % (caught, len(names)))
    return caught == len(names)


