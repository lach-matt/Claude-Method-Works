"""Generate res_gen.h: the eight axis-regular residual components f_ab / rho of P-APPC lem:appc-regular (regform.py),
f_lx and f_nx divided by sqrt(1 - x^2), as a C++ template on the 2-jets of R, m, n, W, s (computed, exact sympy)."""
import sys, sympy as sp
sys.path.insert(0, __file__.rsplit('/', 1)[0])
from regform import regular_components
from gen import polyform

x, ES, OM2 = sp.symbols('x ES OM2')
FN = ('R', 'm', 'n', 'W', 's')
D2 = ('', 'u', 'v', 'x', 'uu', 'uv', 'vv', 'ux', 'vx', 'xx')
J = {f: {d: sp.Symbol(f + ('_' + d if d else '')) for d in D2} for f in FN}
COMP = ('ll', 'ln', 'nn', 'lx', 'nx', 'xx', '11', '22')

def main():
    f = regular_components(x, J, ES, OM2, one=sp.Integer(1))
    exprs = [polyform(sp.expand(f[c])) for c in COMP]
    syms = set().union(*[e.free_symbols for e in exprs]) - {x}
    JET = sorted(str(s) for s in syms)
    repl, red = sp.cse(exprs, symbols=sp.numbered_symbols('t'), optimizations='basic')
    consts = {}
    def K(c):
        c = sp.Rational(c)
        if c not in consts: consts[c] = len(consts)
        return 'K[%d]' % consts[c]
    def pr(e):
        if e.is_Symbol: return str(e)
        if e.is_Rational: return K(e)
        if e.is_Add:
            args = list(e.args); s = pr(args[0])
            for a in args[1:]:
                c, rest = a.as_coeff_Mul()
                s += (' - ' + pr(-a)) if (c.is_Rational and c < 0) else (' + ' + pr(a))
            return '(' + s + ')'
        if e.is_Mul:
            c, rest = e.as_coeff_Mul()
            if c == -1: return '(-' + pr(rest) + ')'
            fs = [K(c)] if c != 1 else []
            fs += [pr(q) for q in sp.Mul.make_args(rest)]
            return '(' + '*'.join(fs) + ')'
        if e.is_Pow:
            b, ex = e.as_base_exp(); assert ex.is_Integer and ex > 0, e
            return '(' + '*'.join([pr(b)] * int(ex)) + ')'
        raise ValueError(e)
    lines = ['  const auto %s = %s;' % (s_, pr(e)) for s_, e in repl]
    lines += ['  out[%d] = %s;' % (i, pr(e)) for i, e in enumerate(red)]
    hdr = ['// generated by gen_res.py: f_ab/rho, ab = ll, ln, nn, lx, nx, xx, 11, 22 (lx, nx divided by sqrt(1 - x^2))',
           '#pragma once', 'static const int RES_NJ = %d;' % len(JET), 'static const int RES_NK = %d;' % len(consts),
           'static const char* RES_JET[] = {%s};' % ', '.join('"%s"' % j for j in JET),
           'static const long RES_KNUM[] = {%s};' % ', '.join(str(int(c.p)) for c in consts),
           'static const long RES_KDEN[] = {%s};' % ', '.join(str(int(c.q)) for c in consts),
           'template<class T, class C> inline void res_eval(const T* J, const C* K, const C& x, T* out) {']
    hdr += ['  const T& %s = J[%d];' % (j, i) for i, j in enumerate(JET)]
    open(sys.argv[1], 'w').write('\n'.join(hdr + lines + ['}']) + '\n')
    print('jets', len(JET), JET, 'temporaries', len(repl), 'mults', sum(l.count('*') for l in lines))

main()
