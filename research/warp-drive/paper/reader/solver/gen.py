"""Generate rhs_gen.h: the axis-regular evolution system as a C++ template (computed from derive.pkl).
Outputs, in this order: m_uv, n_uv, R_uv, W_uv, s_vv.  Inputs (array J): see JET below; every expression is a
polynomial in the inputs (negative powers of R, e^S, e^2W replaced by iR, iES, iOM2), constants from a table K."""
import pickle, sys, sympy as sp

x, ES, OM2 = sp.symbols('x ES OM2')
iR, iES, iOM2 = sp.symbols('iR iES iOM2')
JET = ['x', 'R', 'iR', 'ES', 'iES', 'OM2', 'iOM2',
       'R_u', 'R_v', 'R_x', 'R_xx', 'R_vx', 'W_v', 'W_x', 'W_xx', 'W_vx',
       'm', 'm_u', 'm_v', 'm_x', 'm_xx', 'm_vx', 'n', 'n_u', 'n_v', 'n_x', 'n_xx', 'n_vx',
       's', 's_v', 's_x', 's_vx']

def polyform(e):
    """rewrite negative powers of R, ES, OM2 as positive powers of iR, iES, iOM2"""
    e = sp.expand(e)
    terms = sp.Add.make_args(e)
    out = []
    for t in terms:
        c, rest = t.as_coeff_Mul()
        fac = [c]
        for f in sp.Mul.make_args(rest):
            b, ex = f.as_base_exp()
            if ex.is_Integer and ex < 0:
                inv = {sp.Symbol('R'): iR, ES: iES, OM2: iOM2}[b]
                fac.append(inv ** (-ex))
            else:
                fac.append(f)
        out.append(sp.Mul(*fac))
    return sp.Add(*out)

def main():
    d = pickle.load(open(sys.argv[1], 'rb'))['out']
    r = {k: polyform(d[k][1]) for k in ('E1', 'E2', 'E3', 'E4', 'E5')}
    R = sp.Symbol('R')
    Xm = -OM2 * r['E1']; Xn = -OM2 * r['E2']
    XR = R * (((1 + x) * sp.Symbol('Xm') + (1 - x) * sp.Symbol('Xn')) / 3 - OM2 * r['E3'])
    XW = OM2 * r['E4'] - sp.Rational(3, 2) * iR * sp.Symbol('XR')
    Svv = -8 * ES * OM2 * iR * r['E5']
    exprs = [sp.expand(Xm), sp.expand(Xn), sp.expand(XR), XW, sp.expand(Svv)]
    allsyms = set().union(*[e.free_symbols for e in exprs]) - {sp.Symbol('Xm'), sp.Symbol('Xn'), sp.Symbol('XR')}
    assert allsyms <= set(sp.Symbol(s) for s in JET), allsyms - set(sp.Symbol(s) for s in JET)
    repl, red = sp.cse(exprs, symbols=sp.numbered_symbols('t'), optimizations='basic')
    consts = {}
    def K(c):
        c = sp.Rational(c)
        if c not in consts:
            consts[c] = len(consts)
        return 'K[%d]' % consts[c]
    def pr(e):
        if e.is_Symbol:
            return str(e)
        if e.is_Rational:
            return K(e)
        if e.is_Add:
            args = list(e.args)
            s = pr(args[0])
            for a in args[1:]:
                c, rest = a.as_coeff_Mul()
                if c.is_Rational and c < 0:
                    s += ' - ' + pr(-a)
                else:
                    s += ' + ' + pr(a)
            return '(' + s + ')'
        if e.is_Mul:
            c, rest = e.as_coeff_Mul()
            fs = []
            if c == -1:
                return '(-' + pr(rest) + ')'
            if c != 1:
                fs.append(K(c))
            for f in sp.Mul.make_args(rest):
                fs.append(pr(f))
            return '(' + '*'.join(fs) + ')'
        if e.is_Pow:
            b, ex = e.as_base_exp()
            assert ex.is_Integer and ex > 0, e
            pb = pr(b)
            return '(' + '*'.join([pb] * int(ex)) + ')'
        raise ValueError(e)
    lines = []
    for s_, e in repl:
        lines.append('  const T %s = %s;' % (s_, pr(e)))
    names = ['Xm', 'Xn', 'XR', 'XW', 'Svv']
    for nm, e in zip(names, red):
        lines.append('  const T %s = %s;' % (nm, pr(e)))
    hdr = ['// generated by gen.py from derive.pkl: the axis-regular evolution system', '#pragma once',
           'static const int RHS_NJ = %d;' % len(JET), 'static const int RHS_NK = %d;' % len(consts),
           'static const char* RHS_JET[] = {%s};' % ', '.join('"%s"' % j for j in JET),
           'static const long RHS_KNUM[] = {%s};' % ', '.join(str(int(c.p)) for c in consts),
           'static const long RHS_KDEN[] = {%s};' % ', '.join(str(int(c.q)) for c in consts),
           '// out: m_uv, n_uv, R_uv, W_uv, s_vv',
           'template<class T> inline void rhs_eval(const T* J, const T* K, T* out) {']
    for i, j in enumerate(JET):
        hdr.append('  const T& %s = J[%d];' % (j, i))
    tail = ['  out[0] = Xm; out[1] = Xn; out[2] = XR; out[3] = XW; out[4] = Svv;', '}']
    open(sys.argv[2], 'w').write('\n'.join(hdr + lines + tail) + '\n')
    nmul = sum(l.count('*') for l in lines); nadd = sum(l.count(' + ') + l.count(' - ') for l in lines)
    print('temporaries', len(repl), 'constants', len(consts), 'mults', nmul, 'adds', nadd)

if __name__ == '__main__':
    main()
