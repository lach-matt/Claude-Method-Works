def shape(S):
    """(arity, box size, density)."""
    d = len(next(iter(S)))
    n = 1
    for i in range(d):
        n *= len({c[i] for c in S})
    return d, n, len(S) / n


def _band(x, edges):
    return sum(1 for e in edges if x >= e)


