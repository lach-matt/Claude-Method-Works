# -- the new identity ---------------------------------------------------------

def bisector(D):
    """2(D-2)/(D-3) -- half the amplitude ratio.  None at D = 3."""
    return None if D == 3 else F(2 * (D - 2), D - 3)


def bisector_equals_dimension(lo=2, hi=31):
    return [D for D in range(lo, hi) if bisector(D) is not None
            and bisector(D) == D]


def quadratic_roots():
    """D^2 - 5D + 4 = (D-1)(D-4)."""
    return [d for d in range(-10, 40) if d * d - 5 * d + 4 == 0]


# -- the collision rate -------------------------------------------------------

def family_A(lo=4, hi=41):
    return {D: F(4 * (D - 2), D - 3) for D in range(lo, hi)}


FAMILY_B = {"stationary n": F(9, 2), "cos theta": F(-1, 2), "bisector": F(4),
            "extreme": F(8), "total turning/180": F(1), "s": F(3, 2)}


def small_rationals(qmax=8, top=8):
    return {F(p, q) for q in range(1, qmax + 1) for p in range(0, top * q + 1)}


def collision_stats():
    A = {v for v in family_A().values() if F(0) <= v <= F(8)}
    hits = [k for k, v in FAMILY_B.items() if v in A]
    expected = len(FAMILY_B) * len(A) / len(small_rationals())
    return len(A), len(FAMILY_B), len(small_rationals()), expected, hits


