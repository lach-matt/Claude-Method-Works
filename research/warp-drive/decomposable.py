# ---------------------------------------------- 1. definitions, from scratch

def box_of(X, d):
    return [sorted({x[i] for x in X}) for i in range(d)]


def gen(X):
    S = set(X)
    while True:
        new = set()
        for x, y in itertools.combinations(sorted(S), 2):
            for z in (tuple(map(min, x, y)), tuple(map(max, x, y))):
                if z not in S:
                    new.add(z)
        if not new:
            return frozenset(S)
        S |= new


def joinclose(X):
    S = set(X)
    while True:
        new = {tuple(map(max, x, y)) for x, y in itertools.combinations(sorted(S), 2)} - S
        if not new:
            return frozenset(S)
        S |= new


def phi(X, i, j, a):
    c = [y[i] for y in X if y[j] <= a]
    return max(c) if c else None


def stair(X, box):
    X = sorted(X)
    d = len(box)
    P = {(i, j, a): phi(X, i, j, a)
         for i in range(d) for j in range(d) if i != j for a in box[j]}
    return frozenset(x for x in itertools.product(*box)
                     if all(P[(i, j, x[j])] is not None and x[i] <= P[(i, j, x[j])]
                            for i in range(d) for j in range(d) if i != j))


def kdet(S, box, k):
    d = len(box)
    if k >= d:
        return True
    pr = {T: {tuple(x[i] for i in T) for x in S}
          for T in itertools.combinations(range(d), k)}
    return frozenset(x for x in itertools.product(*box)
                     if all(tuple(x[i] for i in T) in pr[T] for T in pr)) == frozenset(S)


def convex(X, box):
    for i, A in enumerate(box):
        P = sorted({x[i] for x in X})
        if any(v not in P for v in A if P[0] <= v <= P[-1]):
            return False
    return True


def majority(x, y, z):
    return tuple(max(min(a, b), min(b, c), min(c, a)) for a, b, c in zip(x, y, z))


