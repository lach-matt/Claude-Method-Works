FRONTIER = [((3, 3), 9), ((4, 4), 4), ((3, 3, 3), 4), ((2, 2, 2, 2), 5), ((2, 2, 2, 2, 2), 3)]


def exhaustive():
    """T1 over observed boxes, at the stated frontier.  (cases, failures)."""
    cases = fails = 0
    for shape, kmax in FRONTIER:
        allc = list(itertools.product(*[range(a) for a in shape]))
        for k in range(1, kmax + 1):
            for X in itertools.combinations(allc, k):
                X = set(X)
                b = box_of(X, len(shape))
                if len(b) < 2:
                    continue
                cases += 1
                fails += stair(X, b) != gen(X)
    return cases, fails


def witness_check():
    """L3's construction, built rather than inferred.  (cells, failures)."""
    cells = fails = 0
    for shape in ((3, 3), (4, 4)):
        allc = list(itertools.product(*[range(a) for a in shape]))
        for k in range(1, 6):
            for Y in itertools.combinations(allc, k):
                Y = set(Y)
                b = box_of(Y, 2)
                for (a, bb) in stair(Y, b):
                    cells += 1
                    y = next((p for p in Y if p[0] == a), None)
                    z = next((p for p in Y if p[1] == bb), None)
                    u = next((p for p in Y if p[0] <= a and p[1] >= bb), None)
                    v = next((p for p in Y if p[0] >= a and p[1] <= bb), None)
                    if None in (y, z, u, v):
                        fails += 1
                        continue
                    al = (max(y[0], u[0]), max(y[1], u[1]))
                    ga = (max(z[0], v[0]), max(z[1], v[1]))
                    if (al[0], ga[1]) != (a, bb) or al[1] < bb or ga[0] < a \
                       or (min(al[0], ga[0]), min(al[1], ga[1])) != (a, bb):
                        fails += 1
    return cells, fails


def lift_check():
    """L5's conclusion, checked directly.  (sublattices, not-2-determined, majority failures)."""
    n = bad = mbad = 0
    for shape in ((3, 3), (3, 3, 3), (2, 2, 2, 2)):
        allc = list(itertools.product(*[range(a) for a in shape]))
        for k in range(1, 4):
            for X in itertools.combinations(allc, k):
                L = gen(set(X))
                b = box_of(L, len(shape))
                n += 1
                bad += not kdet(L, b, 2)
                for x, y, z in itertools.combinations(sorted(L), 3):
                    if majority(x, y, z) not in L:
                        mbad += 1
    return n, bad, mbad


def convexity_check():
    """N1.  (convex&hold, convex&FAIL, gapped&hold, gapped&FAIL) over DECLARED boxes."""
    ch = cf = gh = gf = 0
    for shape, kmax in (((3, 3), 3), ((4, 4), 3), ((3, 3, 3), 3)):
        box = [list(range(a)) for a in shape]
        allc = list(itertools.product(*box))
        for k in range(1, kmax + 1):
            for X in itertools.combinations(allc, k):
                X = set(X)
                eq = stair(X, box) == gen(X)
                if convex(X, box):
                    ch, cf = ch + eq, cf + (not eq)
                else:
                    gh, gf = gh + eq, gf + (not eq)
    return ch, cf, gh, gf


def bridge(n=400, seed=17):
    """Section 6.  (tested, order+algebra agree, information agrees)."""
    import necindex          # its loader registers the module before exec,
    cy = necindex.cypher     # which cypher.py's @dataclass requires
    opts = {"statistics_order": 2, "algebra_budget": 200000}
    rnd = random.Random(seed)
    tot = oa = inf = 0
    for _ in range(n):
        d = rnd.randint(2, 4)
        alpha = [rnd.randint(2, 3) for _ in range(d)]
        allc = list(itertools.product(*[range(a) for a in alpha]))
        X = sorted(rnd.sample(allc, rnd.randint(2, min(len(allc), 9))))
        co = tuple("c%d" % i for i in range(d))
        vo = {co[i]: sorted({c[i] for c in X}) for i in range(d)}
        ix = cy.Index("b", co, X, value_order=vo)
        Xr = [tuple(ix.code[i][v] for i, v in enumerate(c)) for c in X]
        b = box_of(Xr, d)
        o, _ = cy.op_order(ix, opts)
        a, _ = cy.op_algebra(ix, opts)
        I, _ = cy.op_information(ix, opts)
        if o is None:
            continue
        tot += 1
        oa += frozenset(o) == stair(Xr, b) and frozenset(a) == gen(Xr)
        inf += frozenset(I) == joinclose(Xr)
    return tot, oa, inf


